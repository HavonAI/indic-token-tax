"""Indic Token Tax: measure how many tokens different LLM tokenizers need for the same content
in English, Hindi, Marathi, Hinglish (romanized Hindi), romanized Marathi and every language of India
in FLORES-200.

Reproducible: pinned dataset revisions / checksums, pinned tokenizer revisions, fixed seeds.
Only tokenizer files are downloaded, never model weights. No text is generated by any model.

Usage:
  python measure.py --mecorpus PATH/me_roman.txt [--tokenizer NAME=PATH/tokenizer.json ...]

Outputs: results/results.csv, results/summary.json, results/parity.png, results/indic_parity.csv,
         results/indic_heatmap.png, data/samples/*.txt
"""
