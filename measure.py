TIKTOKEN = {"GPT-4o (o200k_base)": "o200k_base", "GPT-4 (cl100k_base)": "cl100k_base"}

URL_RE = re.compile(r"https?://\S+|www\.\S+")
USER_RE = re.compile(r"@USER\b|@\w+")
WS_RE = re.compile(r"\s+")


# ---- Helpers --------------------------------------------------------------------------------
def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def clean_social(text: str) -> str:
    """Strip mentions, URLs and HTML entities; NFC-normalise; collapse whitespace."""
    text = html.unescape(text)
    text = URL_RE.sub(" ", text)
    text = USER_RE.sub(" ", text)
    text = text.strip().strip('"')
    return WS_RE.sub(" ", unicodedata.normalize("NFC", text)).strip()


def n_words(text: str) -> int:
    return len(text.split())


def sample(lines: list[str], n: int) -> list[str]:
    pool = [x for x in lines if n_words(x) >= MIN_WORDS]
    pool = list(dict.fromkeys(pool))  # dedupe, keep order
    return random.Random(SEED).sample(pool, min(n, len(pool)))


def save_lines(name: str, lines: list[str]) -> None:
    out = DATA / "samples" / f"{name}.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


# ---- Data loaders ---------------------------------------------------------------------------
def load_flores() -> tuple[dict, dict, dict]:
    """FLORES-200 dev + devtest, parallel across eng/hin/mar, plus dev+devtest for every Indic code."""
    archive = DATA / "flores" / "flores200_dataset.tar.gz"
    archive.parent.mkdir(parents=True, exist_ok=True)
    if not archive.exists():
        urllib.request.urlretrieve(FLORES_URL, archive)
    digest = sha256(archive)
    if digest != FLORES_SHA256:
        raise ValueError(f"FLORES checksum mismatch: {digest}")
    out: dict[str, dict[str, list[str]]] = {}
    indic: dict[str, list[str]] = {}
    codes = {"eng": "eng_Latn", **{c: c for c in FLORES_INDIC}}
    with tarfile.open(archive, "r:gz") as tf:
        def read(split: str, code: str) -> list[str]:
            member = tf.extractfile(f"./flores200_dataset/{split}/{code}.{split}")
            rows = member.read().decode("utf-8").splitlines()
            return [unicodedata.normalize("NFC", r.strip()) for r in rows]
        for split in ("dev", "devtest"):
            for lang, code in FLORES_LANGS.items():
                out.setdefault(split, {})[lang] = read(split, code)
            for key, code in codes.items():
                indic.setdefault(key, []).extend(read(split, code))
    for split, langs in out.items():
        if len({len(v) for v in langs.values()}) != 1:
            raise ValueError(f"FLORES {split} not aligned")
    if len({len(v) for v in indic.values()}) != 1:
        raise ValueError("FLORES Indic set not aligned")
    return out, indic, {"source": FLORES_URL, "sha256": digest, "license": "CC-BY-SA-4.0",
                        "splits": {s: len(v["eng"]) for s, v in out.items()},
                        "indic_codes": list(FLORES_INDIC)}


def load_phinc() -> tuple[dict, dict]:
    import pandas as pd
    from huggingface_hub import hf_hub_download

    repo, fname, rev = PHINC
    path = hf_hub_download(repo, fname, repo_type="dataset", revision=rev, cache_dir=str(DATA / "hf"))
    df = pd.read_csv(path).dropna()
    hing, eng = [], []
    for h, e in zip(df["Sentence"].astype(str), df["English_Translation"].astype(str)):
        h, e = clean_social(h), clean_social(e)
        if h and e:
            hing.append(h)
            eng.append(e)
    return {"hin_rom": hing, "eng": eng}, {
        "source": f"hf://datasets/{repo}@{rev}/{fname}", "license": "CC-BY-4.0",
        "rows_raw": int(len(df)), "pairs_used": len(hing)}


def load_hingcorpus() -> tuple[list[str], dict]:
    """Range-fetch the head of the HingCorpus tar.gz and read the first .txt member's lines."""
    head = DATA / "hing" / "head.tar.gz"
    head.parent.mkdir(parents=True, exist_ok=True)
    url = f"https://huggingface.co/datasets/{HING_REPO}/resolve/{HING_REV}/{HING_FILE}"
    if not head.exists():
        req = urllib.request.Request(url, headers={"Range": f"bytes=0-{HING_BYTES - 1}"})
        with urllib.request.urlopen(req) as r:
            head.write_bytes(r.read())
    raw = zlib.decompressobj(16 + zlib.MAX_WBITS).decompress(head.read_bytes())
    off, name = 0, None
    while off + 512 <= len(raw):
        hdr = raw[off:off + 512]
        name = hdr[:100].rstrip(b"\0").decode()
        size = int(hdr[124:136].rstrip(b"\0 ") or b"0", 8)
        if hdr[156:157] in (b"0", b"\0") and name.endswith(".txt"):
            body = raw[off + 512: off + 512 + size]
            break
        off += 512 + ((size + 511) // 512) * 512
    else:
        raise ValueError("no .txt member found in HingCorpus head")
    lines = body.decode("utf-8", errors="ignore").split("\n")[:-1]  # last line may be truncated
    cleaned = [clean_social(x) for x in lines]
    picked = sample(cleaned, N_ROMAN_SAMPLE)
    return picked, {"source": url, "member": name, "bytes_fetched": HING_BYTES,
                    "head_sha256": sha256(head), "lines_read": len(lines), "sampled": len(picked),
                    "license": "not stated on the HF mirror (L3Cube release)"}


def load_mecorpus(path: Path) -> tuple[list[str], dict]:
    with open(path, encoding="utf-8", errors="ignore") as f:
        lines = f.read().split("\n")
    if lines and lines[0].strip().lower() == "text":
        lines = lines[1:]
    cleaned = [clean_social(x) for x in lines]
    picked = sample(cleaned, N_ROMAN_SAMPLE)
    return picked, {"source": path.name, "sha256": sha256(path), "lines_read": len(lines),
                    "sampled": len(picked), "license": "not stated (L3Cube MeCorpus)"}


# ---- Tokenizers -----------------------------------------------------------------------------
def load_tokenizers(extra: list[str]) -> tuple[dict, dict]:
    import tiktoken
    from huggingface_hub import hf_hub_download
    from tokenizers import Tokenizer

    toks, meta = {}, {}
    for name, enc in TIKTOKEN.items():
        e = tiktoken.get_encoding(enc)
        toks[name] = lambda t, e=e: len(e.encode_ordinary(t))
        meta[name] = {"source": f"tiktoken {tiktoken.__version__} {enc}", "vocab": e.n_vocab}
    for name, (repo, rev) in HF_TOKENIZERS.items():
        p = hf_hub_download(repo, "tokenizer.json", revision=rev, cache_dir=str(DATA / "hf"))
        tk = Tokenizer.from_file(p)
        toks[name] = lambda t, tk=tk: len(tk.encode(t, add_special_tokens=False).ids)
        meta[name] = {"source": f"hf://{repo}@{rev}/tokenizer.json", "vocab": tk.get_vocab_size()}
    for spec in extra:
        name, path = spec.split("=", 1)
        tk = Tokenizer.from_file(path)
        toks[name] = lambda t, tk=tk: len(tk.encode(t, add_special_tokens=False).ids)
        meta[name] = {"source": path, "sha256": sha256(Path(path)), "vocab": tk.get_vocab_size()}
    return toks, meta


# ---- Metrics --------------------------------------------------------------------------------
def counts(fn, texts: list[str]) -> np.ndarray:
    return np.array([fn(t) for t in texts], dtype=np.int64)


def basic_stats(texts: list[str], tok: np.ndarray) -> dict:
    words = sum(n_words(t) for t in texts)
    chars = sum(len(t) for t in texts)
    return {"n": len(texts), "tokens": int(tok.sum()), "words": words, "chars": chars,
            "tokens_per_sentence": tok.mean(), "tokens_per_word": tok.sum() / words,
            "chars_per_token": chars / tok.sum()}


def parity(tok_l: np.ndarray, tok_e: np.ndarray) -> dict:
    rng = np.random.default_rng(SEED)
    idx = rng.integers(0, len(tok_l), size=(N_BOOTSTRAP, len(tok_l)))
    boot = tok_l[idx].sum(1) / tok_e[idx].sum(1)
    return {"parity": tok_l.sum() / tok_e.sum(),
            "parity_ci_low": float(np.percentile(boot, 2.5)),
            "parity_ci_high": float(np.percentile(boot, 97.5)),
            "parity_median_sentence": float(np.median(tok_l / np.maximum(tok_e, 1)))}


def run(args) -> None:
    RESULTS.mkdir(exist_ok=True)
    flores, flores_indic, flores_meta = load_flores()
    phinc, phinc_meta = load_phinc()
    hing, hing_meta = load_hingcorpus()
    mer, mer_meta = load_mecorpus(Path(args.mecorpus))
    save_lines("hingcorpus_sample", hing)
    save_lines("mecorpus_sample", mer)
    toks, tok_meta = load_tokenizers(args.tokenizer)

    flores_all = {lang: flores["dev"][lang] + flores["devtest"][lang] for lang in FLORES_LANGS}
    parallel_sets = {"flores_dev": flores["dev"], "flores_devtest": flores["devtest"],
                     "flores_all": flores_all, "phinc": phinc,
                     "flores_indic": flores_indic}  # dev+devtest; lang is the FLORES code
    rows = []
    for tname, fn in toks.items():
        for dname, langs in parallel_sets.items():
            tok_e = counts(fn, langs["eng"])
            for lang, texts in langs.items():
                tok = tok_e if lang == "eng" else counts(fn, texts)
                row = {"tokenizer": tname, "dataset": dname, "lang": lang, "parallel": True,
                       **basic_stats(texts, tok)}
                if lang != "eng":
                    row.update(parity(tok, tok_e))
                rows.append(row)
        for dname, lang, texts in (("hingcorpus", "hin_rom", hing), ("mecorpus", "mar_rom", mer)):
            rows.append({"tokenizer": tname, "dataset": dname, "lang": lang, "parallel": False,
                         **basic_stats(texts, counts(fn, texts))})
        print(f"done {tname}")

    fields = ["tokenizer", "dataset", "lang", "parallel", "n", "tokens", "words", "chars",
              "tokens_per_sentence", "tokens_per_word", "chars_per_token", "parity",
              "parity_ci_low", "parity_ci_high", "parity_median_sentence"]
    with open(RESULTS / "results.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in rows:
            w.writerow({k: (round(v, 4) if isinstance(v, float) else v) for k, v in r.items()})

    def pick(d, lang, key):
        return next(round(float(r[key]), 3) for r in rows if r["tokenizer"] == tn
                    and r["dataset"] == d and r["lang"] == lang)

    summary = {"seed": SEED, "bootstrap": N_BOOTSTRAP, "datasets": {
        "flores200": flores_meta, "phinc": phinc_meta, "hingcorpus": hing_meta, "mecorpus": mer_meta},
        "tokenizers": tok_meta, "reference_english": REF_TOKENIZER, "headline": {}}
    tn = REF_TOKENIZER
    ref_eng = pick("flores_all", "eng", "tokens_per_sentence")
    for tn in toks:
        summary["headline"][tn] = {
            "tps_eng_flores": pick("flores_all", "eng", "tokens_per_sentence"),
            "tps_hin_flores": pick("flores_all", "hin", "tokens_per_sentence"),
            "tps_mar_flores": pick("flores_all", "mar", "tokens_per_sentence"),
            "mar_vs_ref_english": round(pick("flores_all", "mar", "tokens_per_sentence") / ref_eng, 3),
            "hin_vs_ref_english": round(pick("flores_all", "hin", "tokens_per_sentence") / ref_eng, 3),
            "parity_hin_flores": pick("flores_all", "hin", "parity"),
            "parity_mar_flores": pick("flores_all", "mar", "parity"),
            "parity_hinglish_phinc": pick("phinc", "hin_rom", "parity"),
            "tpw_eng_flores": pick("flores_all", "eng", "tokens_per_word"),
            "tpw_hin_flores": pick("flores_all", "hin", "tokens_per_word"),
            "tpw_mar_flores": pick("flores_all", "mar", "tokens_per_word"),
            "tpw_eng_phinc": pick("phinc", "eng", "tokens_per_word"),
            "tpw_hinglish_phinc": pick("phinc", "hin_rom", "tokens_per_word"),
            "tpw_hinglish_hingcorpus": pick("hingcorpus", "hin_rom", "tokens_per_word"),
            "tpw_mar_rom_mecorpus": pick("mecorpus", "mar_rom", "tokens_per_word"),
        }
    summary["indic"] = write_indic(rows, list(toks))
    (RESULTS / "summary.json").write_text(json.dumps(summary, indent=2, default=float), encoding="utf-8")
    plot(rows, list(toks))
    plot_indic(rows, list(toks))


def indic_rows(rows: list[dict], tname: str) -> dict:
    return {r["lang"]: r for r in rows if r["tokenizer"] == tname and r["dataset"] == "flores_indic"}


def write_indic(rows: list[dict], order: list[str]) -> dict:
    """results/indic_parity.csv (long format) and a per-tokenizer summary for summary.json."""
    ref_eng = indic_rows(rows, REF_TOKENIZER)["eng"]["tokens"]
    out, summ = [], {}
    for tn in order:
        rs = indic_rows(rows, tn)
        for code, name in FLORES_INDIC.items():
            r = rs[code]
            out.append({"tokenizer": tn, "lang": code, "language": name, "tokens": r["tokens"],
                        "chars_per_token": round(r["chars_per_token"], 4),
                        "parity": round(r["parity"], 4), "parity_ci_low": round(r["parity_ci_low"], 4),
                        "parity_ci_high": round(r["parity_ci_high"], 4),
                        "vs_ref_english": round(r["tokens"] / ref_eng, 4)})
        ps = {c: float(rs[c]["parity"]) for c in FLORES_INDIC}
        summ[tn] = {"median_parity": round(float(np.median(list(ps.values()))), 3),
                    "max_parity": round(max(ps.values()), 3), "max_parity_lang": max(ps, key=ps.get),
                    "min_parity": round(min(ps.values()), 3), "min_parity_lang": min(ps, key=ps.get)}
    with open(RESULTS / "indic_parity.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(out[0]))
        w.writeheader()
        w.writerows(out)
    return summ


def plot_indic(rows: list[dict], order: list[str]) -> None:
    """Heatmap of parity (own English baseline), tokenizers x FLORES Indic languages."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import LogNorm

    langs = list(FLORES_INDIC)
    mat = np.array([[float(indic_rows(rows, t)[c]["parity"]) for c in langs] for t in order])
    ti = np.argsort(np.median(mat, axis=1), kind="stable")  # rows: lowest median parity first
    li = np.argsort(np.median(mat, axis=0), kind="stable")  # columns: cheapest language first
    mat = mat[ti][:, li]
    tnames = [order[i] for i in ti]
    lnames = [f"{FLORES_INDIC[langs[j]]} ({langs[j]})" for j in li]
    fig, ax = plt.subplots(figsize=(16, 6.4))
    im = ax.imshow(mat, cmap="YlOrRd", norm=LogNorm(vmin=1.0, vmax=max(10.0, mat.max())), aspect="auto")
    for i in range(mat.shape[0]):
        for j in range(mat.shape[1]):
            v = mat[i, j]
            ax.text(j, i, f"{v:.1f}" if v >= 10 else f"{v:.2f}", ha="center", va="center",
                    fontsize=7, color="white" if v >= 4 else "#222")
    ax.set_xticks(range(len(lnames)), lnames, rotation=55, ha="right", fontsize=8)
    ax.set_yticks(range(len(tnames)), tnames, fontsize=9)
    cb = fig.colorbar(im, ax=ax, fraction=0.025, pad=0.01)
    cb.set_label("Parity ratio vs English (log scale)", fontsize=8)
    ax.set_title("Token parity vs English on FLORES-200 dev+devtest (2,009 sentences per language). "
                 "Each tokenizer vs its own English count; higher = more tokens for the same content.",
                 fontsize=10)
    fig.tight_layout()
    fig.savefig(RESULTS / "indic_heatmap.png", dpi=200)


def plot(rows: list[dict], order: list[str]) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    series = [("Marathi (FLORES-200)", "flores_all", "mar", "#1f5aa6"),
              ("Hindi (FLORES-200)", "flores_all", "hin", "#e07b39"),
              ("Hinglish (PHINC)", "phinc", "hin_rom", "#5a9e6f")]
    order = sorted(order, key=lambda t: -next(r["parity"] for r in rows if r["tokenizer"] == t
                                              and r["dataset"] == "flores_all" and r["lang"] == "mar"))
    x = np.arange(len(order))
    width = 0.27
    fig, ax = plt.subplots(figsize=(12, 5.5))
    for i, (label, d, lang, color) in enumerate(series):
        sel = [next(r for r in rows if r["tokenizer"] == t and r["dataset"] == d and r["lang"] == lang)
               for t in order]
        vals = [r["parity"] for r in sel]
        err = [[v - r["parity_ci_low"] for v, r in zip(vals, sel)],
               [r["parity_ci_high"] - v for v, r in zip(vals, sel)]]
        bars = ax.bar(x + (i - 1) * width, vals, width, yerr=err, label=label, color=color, capsize=2)
        for b, v in zip(bars, vals):
            ax.text(b.get_x() + b.get_width() / 2, v + 0.04, f"{v:.2f}", ha="center", fontsize=7)
    ax.axhline(1.0, color="#333", lw=1, ls="--", label="Parity with English (1.0)")
    ax.set_xticks(x, order, rotation=20, ha="right", fontsize=9)
    ax.set_ylabel("Tokens for same content / tokens in English")
    ax.set_title("Token parity ratio vs English (higher = more tokens for the same meaning)\n"
                 "Error bars: 95% bootstrap CI. Each tokenizer is compared with its own English count.",
                 fontsize=11)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(frameon=False, fontsize=9)
    fig.tight_layout()
    fig.savefig(RESULTS / "parity.png", dpi=150)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mecorpus", required=True, help="path to L3Cube MeCorpus me_roman.txt")
    ap.add_argument("--tokenizer", action="append", default=[],
                    help="extra local tokenizer as NAME=path/to/tokenizer.json (repeatable)")
    run(ap.parse_args())
